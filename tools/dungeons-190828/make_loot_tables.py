"""
Writes the loot tables of the recreated dungeons (loot_tables\\dungeon_*.json) from the dungeon maps.

Why: in the client data of the installed build the dungeon units carry no loot, so every dungeon enemy fell back to
the "normal" table (85% chance of nothing) and the chests, the Big Treasure and the minibosses often dropped nothing,
while walls, barrels and bombs dropped bags like regular enemies.

  dungeon_no_loot      walls, wrecks, barrels, bombs, mines and the DPS chest itself: drop nothing
  dungeon_chest        treasure chests (and the "dud" of a Big Treasure): one item and a chance of more
  dungeon_chest_big    the Big Treasure reward: three items, vapor and scrap
  dungeon_miniboss     minibosses: a guaranteed usable item and extras

Bosses keep using the "boss" table of items.json. The "tier" of each item is relative to the unit (1 = same tier).
Units are listed by exact template name, so nothing here touches the tutorial or the open world.

Usage: python make_loot_tables.py <maps folder> <loot_tables folder>
"""

import glob
import json
import os
import sys

from unit_types import units


def collect(maps_dir):
    cats = {"no_loot": set(), "chest": set(), "chest_big": set(), "miniboss": set()}
    for path in sorted(glob.glob(os.path.join(maps_dir, "dungeon_*.json"))):
        with open(path, encoding="utf-8") as f:
            m = json.load(f)
        for tid, t in m.get("types", {}).items():
            tpl = t.get("template", tid)
            role = units().get(tpl, {}).get("role", "")
            low = tpl.lower()
            if t.get("miniboss"):
                cats["miniboss"].add(tpl)
            elif low.endswith("_reward"):
                cats["chest_big"].add(tpl)
            elif low.endswith("treasurebig") or low.endswith("death") or role in ("wall", "wreck") \
                    or low in ("bombbarrel", "firebarrel") or low.endswith("boom") or "exploder" in low \
                    or t.get("behavior") == "kamikaze":
                cats["no_loot"].add(tpl)
            elif role == "treasure" or "treasure" in low:
                cats["chest"].add(tpl)
    return {k: sorted(v) for k, v in cats.items()}


HEAD = "// Generated by tools\\dungeons-190828\\make_loot_tables.py (you can edit by hand; running the script again overwrites it).\n"


def write(folder, name, description, units_list, rolls):
    table = {"id": name, "description": description, "units": units_list, "rolls": rolls}
    with open(os.path.join(folder, name + ".json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD + json.dumps(table, indent=2, ensure_ascii=False) + "\n")


def item(tier=None, slot=None):
    d = {}
    if slot:
        d["slot"] = slot
    if tier:
        d["tier"] = tier
    return d


def scrap(n):
    return {"instant": {"currency_id": "newscrap", "currency_amount": n}}


def main(maps_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    c = collect(maps_dir)

    write(out_dir, "dungeon_no_loot", "Walls, wrecks, barrels, bombs, mines and the DPS chest: drop nothing.",
          c["no_loot"], [{"lootTable": [{"weight": 1}]}])

    write(out_dir, "dungeon_chest", "Dungeon chest: one item (of the chest's tier, sometimes one above), a chance of an extra, of health and of scrap.",
          c["chest"], [
              {"usableChance": 70, "lootTable": [
                  {"weight": 60, "items": [item(1)]}, {"weight": 40, "items": [item(2)]}]},
              {"usableChance": 40, "lootTable": [
                  {"weight": 55}, {"weight": 35, "items": [item(1)]}, {"weight": 10, "items": [item(2)]}]},
              {"lootTable": [
                  {"weight": 50}, {"weight": 35, "items": [item(1, "Health")]}, {"weight": 15, "items": [item(1, "Energy")]}]},
              {"lootTable": [{"weight": 70}, {"weight": 30, "items": [scrap(10)]}]},
          ])

    write(out_dir, "dungeon_chest_big", "Big Treasure reward (broken in time): three items, health and scrap.",
          c["chest_big"], [
              {"usableChance": 100, "lootTable": [{"weight": 1, "items": [item(2)]}]},
              {"usableChance": 50, "lootTable": [
                  {"weight": 60, "items": [item(2)]}, {"weight": 40, "items": [item(3)]}]},
              {"lootTable": [
                  {"weight": 50, "items": [item(1)]}, {"weight": 50, "items": [item(2)]}]},
              {"lootTable": [{"weight": 30}, {"weight": 70, "items": [item(2, "Health")]}]},
              {"lootTable": [{"weight": 1, "items": [scrap(50)]}]},
          ])

    write(out_dir, "dungeon_miniboss", "Dungeon miniboss: one item the class uses (one tier above), an extra, health and scrap.",
          c["miniboss"], [
              {"usableChance": 100, "lootTable": [{"weight": 1, "items": [item(2)]}]},
              {"lootTable": [
                  {"weight": 50}, {"weight": 35, "items": [item(1)]}, {"weight": 15, "items": [item(2)]}]},
              {"lootTable": [{"weight": 40}, {"weight": 60, "items": [item(2, "Health")]}]},
              {"lootTable": [{"weight": 70}, {"weight": 30, "items": [scrap(25)]}]},
          ])

    for k, v in c.items():
        print("%-10s %3d unidade(s): %s" % (k, len(v), ", ".join(v)[:200]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
